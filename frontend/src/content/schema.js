// Turns a title into a page address: "IT Consultancy" -> "it-consultancy"
export const slugify = (value) =>
  String(value || '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);

/** New services get their page address from the title, kept unique; existing addresses are left alone. */
const normalizeServices = (form) => {
  const taken = new Set();
  const items = (form.items || []).map((item) => {
    let id = slugify(item.id) || slugify(item.title) || 'service';
    const base = id;
    for (let n = 2; taken.has(id); n += 1) id = `${base}-${n}`;
    taken.add(id);
    return id === item.id ? item : { ...item, id };
  });
  return { ...form, items };
};

