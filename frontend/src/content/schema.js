// Describes what the admin can edit on each page: the form in Website → Site content is built from this.
//
// A section groups fields. A field is { type, path, label, hint?, ... }, where `path` says where its value is
// kept in the page's content (e.g. 'hero.title'); it must match content/defaults.js.
//   type: 'text' | 'textarea' | 'link' | 'image' | 'icon' | 'number' | 'select' | 'weekdays' | 'theme'
//       | 'strings' (a list of short lines)
//       | 'list' (a list of cards: `fields` describe each card, `titleField` is the path shown as its heading)
// Add a page here (and to CONTENT_PAGES in backend/cms/models.py and to content/defaults.js) to make it editable.

const toggle = (path, label, extra) => ({ type: 'toggle', path, label, ...extra });
// A heading inside a list card, to break a long form into parts
const divider = (label, hint) => ({ type: 'heading', path: `_${label}`, label, hint });
const text = (path, label, extra) => ({ type: 'text', path, label, ...extra });
const area = (path, label, extra) => ({ type: 'textarea', path, label, rows: 3, ...extra });
const link = (path, label, extra) => ({ type: 'link', path, label, hint: 'A page on this site, like /services, or a full web address.', ...extra });
const image = (path, label, extra) => ({ type: 'image', path, label, ...extra });
const icon = (path = 'icon', label = 'Icon') => ({ type: 'icon', path, label });
const strings = (path, label, extra) => ({ type: 'strings', path, label, ...extra });

// Wording shared by many sections: {location}, {name}, {tagline} are filled in from the site-wide details
